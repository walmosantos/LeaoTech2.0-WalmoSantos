let opcao = prompt('Digite a opção que quer executar (A - D)')

switch (opcao) {
    case "A":
    console.log('Exelente desempenho')
    break;

     case "B":
    console.log('Bom desempenho')
    break;

    case "C":
    console.log('Desempenho regular')
    break;

    case "D":
    console.log('Desempenho insuficiente')
    break;

    default:
    console.log('Op. INVALIDA')
}